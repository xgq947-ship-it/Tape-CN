import Foundation

/// A classic 5 × 7 dot-matrix face, the kind stock tickers have scrolled since the seventies.
/// Rows run top to bottom; `#` is a lit LED.
nonisolated enum LEDFont {
    static let rows = 7

    struct Glyph: Sendable {
        let width: Int
        /// lit[row][column], row 0 at the top.
        let lit: [[Bool]]
    }

    static func glyph(for character: Character) -> Glyph {
        glyphs[character] ?? glyphs[Character(character.uppercased())] ?? glyphs["?"]!
    }

    /// Columns between glyphs.
    static let tracking = 1

    /// Lit dots for a line of text, left to right; also returns the width in columns.
    static func layout(_ text: String) -> (columns: Int, dots: [(column: Int, row: Int)]) {
        var dots: [(Int, Int)] = []
        var x = 0
        for (index, character) in text.enumerated() {
            let glyph = glyph(for: character)
            for row in 0..<rows {
                for column in 0..<glyph.width where glyph.lit[row][column] { dots.append((x + column, row)) }
            }
            x += glyph.width
            if index < text.count - 1 { x += tracking }
        }
        return (x, dots)
    }

    private static func parse(_ pattern: [String]) -> Glyph {
        precondition(pattern.count == rows)
        let width = pattern.map(\.count).max() ?? 0
        let lit = pattern.map { row in (0..<width).map { index in index < row.count && Array(row)[index] == "#" } }
        return Glyph(width: width, lit: lit)
    }

